"""Render the rule reference pages (docs/rules/) from aetheris/rules/*.yaml.

Usage: python scripts/gen_rules_docs.py [output_dir]

The output is deterministic: rules keep the order of their YAML file, agents the order of
AGENT_IDS, and nothing depends on the date or the machine. tests/test_docs.py regenerates
the pages into a temporary directory and fails when docs/rules/ is stale.
"""

import sys
from collections import Counter
from pathlib import Path

from aetheris.domain import SEVERITIES, Agent
from aetheris.registry import AGENTS

DEFAULT_OUT = Path(__file__).resolve().parent.parent / "docs" / "rules"
RULES_URL = "https://github.com/adryserage/aetheris/blob/main/aetheris/rules"
NOTICE = (
    "<!-- Generated by scripts/gen_rules_docs.py from aetheris/rules/*.yaml. Do not edit. -->\n"
)


def _plural(count: int, word: str) -> str:
    return f"{count} {word}" if count == 1 else f"{count} {word}s"


def _text(value: str) -> str:
    return " ".join(value.split())


def render_agent(agent: Agent) -> str:
    checks = ", ".join(f"`{c}`" for c in agent.checks) or "none"
    lines = [
        NOTICE,
        f"# {agent.name} rules",
        "",
        _text(agent.summary),
        "",
        f"- Agent id: `{agent.id}`",
        f"- Rules: {len(agent.rules)} (source: [`{agent.id}.yaml`]({RULES_URL}/{agent.id}.yaml))",
        f"- Deterministic checks: {checks}",
        "",
    ]
    for rule in agent.rules:
        languages = ", ".join(rule.languages) or "all"
        lines += [
            f"## {rule.id}: {rule.title}",
            "",
            f"- Severity: {rule.severity}",
            f"- Languages: {languages}",
        ]
        if rule.references:
            lines.append("- References: " + ", ".join(rule.references))
        lines += ["", _text(rule.check), ""]
    return "\n".join(lines)


def render_index() -> str:
    rows = ["| Agent | Rules | Highest severity |", "| --- | --- | --- |"]
    for agent in AGENTS.values():
        top = Counter(r.severity for r in agent.rules)
        highest = next((s for s in SEVERITIES if top[s]), "none")
        rows.append(f"| [{agent.name}]({agent.id}.md) | {len(agent.rules)} | {highest} |")
    total = sum(len(a.rules) for a in AGENTS.values())
    return "\n".join(
        [
            NOTICE,
            "# Rules reference",
            "",
            f"The {_plural(len(AGENTS), 'agent')} hold {total} rules. Each rule has an id, a "
            "severity, the languages it applies to and the text of the check your assistant "
            "performs. A finding from a deterministic check carries the id of its rule when one "
            "applies. See [Agents](../agents.md) for the checks.",
            "",
            *rows,
            "",
            "These pages are generated from the YAML files in "
            f"[`aetheris/rules/`]({RULES_URL}).",
            "",
        ]
    )


def render_all(out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    pages = {"index.md": render_index()}
    pages |= {f"{a.id}.md": render_agent(a) for a in AGENTS.values()}
    for stale in out_dir.glob("*.md"):
        if stale.name not in pages:
            stale.unlink()
    written = []
    for name, text in pages.items():
        path = out_dir / name
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def main(argv: list[str]) -> int:
    out_dir = Path(argv[0]) if argv else DEFAULT_OUT
    for path in render_all(out_dir):
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
